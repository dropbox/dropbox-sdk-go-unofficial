func TestHasherChunkBoundaries(t *testing.T) {
	blockSize := contenthash.BlockSize
	tests := [][]int{
		{0},
		{100},
		{100, 10},
		{blockSize - 1},
		{blockSize},
		{blockSize + 1},
		{blockSize - 2, 1},
		{blockSize - 2, 2},
		{blockSize - 2, 3},
		{5, 5, 5, blockSize},
		{blockSize + 1, blockSize - 1, 7},
	}

	data := deterministicBytes(longestTotal(tests))
	for _, chunks := range tests {
		t.Run(fmt.Sprint(chunks), func(t *testing.T) {
			h := contenthash.New()
			pos := 0
			for _, chunkSize := range chunks {
				n, err := h.Write(data[pos : pos+chunkSize])
				if err != nil {
					t.Fatalf("Write returned error: %v", err)
				}
				if n != chunkSize {
					t.Fatalf("Write returned %d, want %d", n, chunkSize)
				}
				pos += chunkSize
			}

			got := h.HexDigest()
			want := referenceContentHash(data[:pos])
			if got != want {
				t.Fatalf("HexDigest = %q, want %q", got, want)
			}
			if gotAgain := h.HexDigest(); gotAgain != want {
				t.Fatalf("second HexDigest = %q, want %q", gotAgain, want)
			}
		})
	}
}

func TestHasherReset(t *testing.T) {
	h := contenthash.New()
	_, err := h.Write([]byte("first"))
	if err != nil {
		t.Fatalf("Write returned error: %v", err)
	}
	h.Reset()

	_, err = h.Write([]byte("second"))
	if err != nil {
		t.Fatalf("Write returned error: %v", err)
	}

	want := referenceContentHash([]byte("second"))
	if got := h.HexDigest(); got != want {
		t.Fatalf("HexDigest after Reset = %q, want %q", got, want)
	}

	h.Reset()
	_, err = h.Write(deterministicBytes(contenthash.BlockSize))
	if err != nil {
		t.Fatalf("Write returned error: %v", err)
	}
	h.Reset()
	if got, want := h.HexDigest(), referenceContentHash(nil); got != want {
		t.Fatalf("HexDigest after flushed block Reset = %q, want %q", got, want)
	}
}

func TestHasherZeroValue(t *testing.T) {
	var h contenthash.Hasher

	if got, want := h.HexDigest(), referenceContentHash(nil); got != want {
		t.Fatalf("zero value HexDigest = %q, want %q", got, want)
	}

	_, err := h.Write([]byte("zero value"))
	if err != nil {
		t.Fatalf("Write returned error: %v", err)
	}

	want := referenceContentHash([]byte("zero value"))
	if got := h.HexDigest(); got != want {
		t.Fatalf("zero value HexDigest after Write = %q, want %q", got, want)
	}

	h.Reset()
	if got, want := h.HexDigest(), referenceContentHash(nil); got != want {
		t.Fatalf("zero value HexDigest after Reset = %q, want %q", got, want)
	}
}

func TestHasherHashInterfaceProperties(t *testing.T) {
	h := contenthash.New()
	if got := h.Size(); got != sha256.Size {
		t.Fatalf("Size = %d, want %d", got, sha256.Size)
	}
	if got := h.BlockSize(); got != contenthash.BlockSize {
		t.Fatalf("BlockSize = %d, want %d", got, contenthash.BlockSize)
	}

	prefix := []byte("prefix:")
	sum := h.Sum(prefix)
	if got, want := string(sum[:len(prefix)]), string(prefix); got != want {
		t.Fatalf("Sum prefix = %q, want %q", got, want)
	}
	if got, want := len(sum)-len(prefix), h.Size(); got != want {
		t.Fatalf("Sum appended %d bytes, want %d", got, want)
	}
}

func TestComputeReturnsReadError(t *testing.T) {
	readErr := errors.New("read failed")
	_, err := contenthash.Compute(errorReader{err: readErr})
	if !errors.Is(err, readErr) {
		t.Fatalf("Compute error = %v, want %v", err, readErr)
	}
}

type errorReader struct {
	err error
}

func (r errorReader) Read([]byte) (int, error) {
	return 0, r.err
}

func referenceContentHash(data []byte) string {
	overall := sha256.New()
	for len(data) > 0 {
		n := contenthash.BlockSize
		if len(data) < n {
			n = len(data)
		}

		blockHash := sha256.Sum256(data[:n])
		_, _ = overall.Write(blockHash[:])
		data = data[n:]
	}
	return hex.EncodeToString(overall.Sum(nil))
}

func deterministicBytes(n int) []byte {
	data := make([]byte, n)
	for i := range data {
		data[i] = byte((i*31 + 7) % 251)
	}
	return data
}

func longestTotal(tests [][]int) int {
	longest := 0
	for _, test := range tests {
		total := 0
		for _, n := range test {
			total += n
		}
		if total > longest {
			longest = total
		}
	}
	return longest
}

var _ io.Reader = errorReader{}

func TestComputeKnownVectors(t *testing.T) {
	for _, test := range []struct {
		name string
		data string
		want string
	}{
		{
			name: "empty",
			data: "",
			want: "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855",
		},
		{
			name: "single byte",
			data: "a",
			want: "bf5d3affb73efd2ec6c36ad3112dd933efed63c4e1cbffcfa88e2759c144f2d8",
		},
		{
			name: "short string",
			data: "abc",
			want: "4f8b42c22dd3729b519ba6f68d2da7cc5b2d606d05daed5ad5128cc03e6c6358",
		},
		{
			name: "longer string",
			data: "hello world",
			want: "bc62d4b80d9e36da29c16c5d4d9f11731f36052c72401a76c23c0fb5a9b74423",
		},
	} {
		t.Run(test.name, func(t *testing.T) {
			got, err := contenthash.Compute(strings.NewReader(test.data))
			if err != nil {
				t.Fatalf("Compute returned error: %v", err)
			}
			if got != test.want {
				t.Fatalf("Compute = %q, want %q", got, test.want)
			}
		})
	}
}

